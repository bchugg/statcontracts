"""
Gaussian deferred values from tilted overshoots, with joint confidence bounds.

The CGF-optimal rule's deferred value J, relative to the upper bound
U = 1 / (e rho*), is an expectation of (1 + rho O) exp(-rho O) over the
overshoot O under the exponentially tilted Gaussian law. The four settings
(theta = 0.3, sigma = 0.5, C = E_0 = 1, R_0 = 0) and the seed are fixed
before simulation. Every path runs until it crosses the threshold, with no
time cap or state grid. One-sided Hoeffding bounds with error probability
.01/4 per row give simultaneous 99% lower bounds on J / U, rounded down to
three decimals. Confidence is for Monte Carlo sampling only.

Writes results/gaussian_overshoot.json and results/gaussian_overshoot_table.tex.
"""

import json
import math

import numpy as np

from common import save_text


DELTAS = (0.9, 0.95, 0.98, 0.995)
THETA, SIGMA = 0.3, 0.5
N_PATHS, SEED, ALPHA = 400_000, 20261017, 0.01


def simulate(delta, rng):
    loss = -math.log(delta)
    rho = loss / (2 * (THETA**2 + 2 * loss * SIGMA**2))
    lam = 4 * THETA + 8 * SIGMA**2 * loss / THETA
    mean = lam * THETA - lam**2 / 8
    variance = lam**2 * SIGMA**2
    tilted_mean = mean + rho * variance
    assert abs(rho * mean + rho**2 * variance / 2 - loss) < 1e-12
    assert mean > 0  # The uncapped rule is admissible under the original law.

    threshold = 1 / rho  # C = E_0 = 1; no reward is payable at time zero.
    active = np.zeros(N_PATHS)
    overshoot = np.empty(N_PATHS)
    completed = steps = 0
    while active.size:
        active += rng.normal(tilted_mean, math.sqrt(variance), active.size)
        crossed = active >= threshold
        count = int(crossed.sum())
        overshoot[completed:completed + count] = active[crossed] - threshold
        completed += count
        active = active[~crossed]
        steps += 1

    scaled = rho * overshoot
    samples = (1 + scaled) * np.exp(-scaled)
    assert completed == N_PATHS and np.all((samples >= 0) & (samples <= 1))
    margin = math.sqrt(math.log(len(DELTAS) / ALPHA) / (2 * N_PATHS))
    lower = max(0.0, float(samples.mean()) - margin)
    return {
        "delta": delta, "rho": rho, "lambda": lam,
        "original_drift": mean, "tilted_drift": tilted_mean,
        "mean_ratio": float(samples.mean()),
        "standard_error": float(samples.std(ddof=1) / math.sqrt(N_PATHS)),
        "hoeffding_margin": margin, "lower_bound": lower,
        "lower_rounded_down": math.floor(1000 * lower) / 1000,
        "second_moment_estimate": float(np.mean(overshoot**2)),
        "maximum_crossing_time": steps,
    }


def main():
    children = np.random.SeedSequence(SEED).spawn(len(DELTAS))
    rows = [simulate(delta, np.random.default_rng(seed))
            for delta, seed in zip(DELTAS, children)]
    record = {
        "theta": THETA, "sigma": SIGMA, "C": 1, "r0": 0, "e0": 1,
        "paths_per_setting": N_PATHS, "seed": SEED,
        "simultaneous_confidence": 1 - ALPHA, "results": rows,
    }
    save_text("gaussian_overshoot.json", json.dumps(record, indent=2) + "\n")
    lines = [r"% Generated by experiments/sequential/gaussian_overshoot.py.",
             r"\begin{tabular}{rrrr}", r"\hline",
             r"$\delta$ & $\rho^*$ & Estimated $J/U_{\dfrd}(1)$ & 99\% lower bound \\",
             r"\hline"]
    for row in rows:
        lines.append(f"{row['delta']:.3f} & {row['rho']:.4f} & "
                     f"{row['mean_ratio']:.4f} & {row['lower_rounded_down']:.3f} " + r"\\")
    lines += [r"\hline", r"\end{tabular}"]
    save_text("gaussian_overshoot_table.tex", "\n".join(lines) + "\n")
    print(json.dumps(record, indent=2))


if __name__ == "__main__":
    main()
