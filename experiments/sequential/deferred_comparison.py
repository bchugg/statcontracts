"""
Deferred Bernoulli payoffs without a state grid or Monte Carlo.

Reproduces the large-upward-jump example (p = 0.02, m = 0.01, delta = 0.9),
where the CGF-optimal rule loses at least 29.4% relative to the optimum, and
compares feasible capped policies directly with the analytical adaptive upper
bound 1 / (e rho*) at p = 0.7, m = 0.5 and four discount factors. Values come
from first-passage recursion (statcontracts.sequential.capped_threshold_value),
including the signed payoff on paths that reach the deterministic cap.

Writes results/deferred_comparison.json, results/large_jump_table.tex, and
results/deferred_upper_table.tex.
"""

import json
import math

from statcontracts.sequential import (
    BettingReward,
    beta_threshold,
    capped_threshold_value,
)

from common import save_text


def experiment():
    result = {"C": 1, "large_jump": {}, "upper_bound_comparison": []}
    p, m, delta = .02, .01, .9
    reward = BettingReward(p, m)
    rho, bet = reward.interior_cgf_optimal(delta)
    upper = 1 / (math.e * rho)
    large = {"p": p, "m": m, "delta": delta, "rho": rho,
             "upper": upper, "strategies": {}}
    for name, lam, threshold in (
            ("cgf", bet, 1 / rho),
            ("cgf_exact", bet, beta_threshold(reward, bet, delta)),
            ("feasible_exact", 15.5, beta_threshold(reward, 15.5, delta))):
        row = capped_threshold_value(reward, lam, delta, threshold, horizon=600)
        row.update({"lambda": lam, "threshold": threshold,
                    "value_over_upper": row["value"] / upper})
        large["strategies"][name] = row
    result["large_jump"] = large

    for delta in (.9, .95, .98, .995):
        p, m = .7, .5
        reward = BettingReward(p, m)
        rho, bet = reward.interior_cgf_optimal(delta)
        growth = reward.growth_optimal_lambda()
        upper = 1 / (math.e * rho)
        row = {"p": p, "m": m, "delta": delta, "rho": rho, "upper": upper,
               "strategies": {}}
        for name, lam, threshold in (
                ("drift", growth, reward.drift() / -math.log(delta)),
                ("cgf_at_growth", growth, 1 / reward.cgf_root(delta)),
                ("cgf_optimal", bet, 1 / rho)):
            value = capped_threshold_value(reward, lam, delta, threshold)
            value.update({"lambda": lam, "threshold": threshold,
                          "value_over_upper": value["value"] / upper})
            assert value["value"] <= upper + 1e-10
            row["strategies"][name] = value
        result["upper_bound_comparison"].append(row)
    return result


def write_tables(result):
    lines = [r"% Generated by experiments/sequential/deferred_comparison.py.",
             r"\begin{tabular}{lrrr}", r"\hline",
             r"Parameter and threshold & $\lambda$ & Log-reward threshold & Value \\",
             r"\hline"]
    labels = {"cgf": "CGF parameter and threshold",
              "cgf_exact": "CGF parameter, exact threshold",
              "feasible_exact": "Another fixed parameter, exact threshold"}
    for name, row in result["large_jump"]["strategies"].items():
        lines.append(f"{labels[name]} & {row['lambda']:.4f} & "
                     f"{row['threshold']:.5f} & {row['value']:.6f}" + r" \\")
    lines += [r"\hline", r"\end{tabular}"]
    save_text("large_jump_table.tex", "\n".join(lines) + "\n")

    lines = [r"% Generated by experiments/sequential/deferred_comparison.py.",
             r"\begin{tabular}{rrrrr}", r"\hline",
             r"$\delta$ & $U_{\dfrd}(1)$ & Drift at $\lambdagro$ & "
             r"CGF at $\lambdagro$ & CGF-optimal \\",
             r"\hline"]
    for row in result["upper_bound_comparison"]:
        fields = [f"{row['delta']:g}", f"{row['upper']:.4f}"]
        # Round ratios down, so displayed fractions do not overstate them.
        fields += [f"{math.floor(1000 * row['strategies'][name]['value_over_upper']) / 1000:.3f}"
                   for name in ("drift", "cgf_at_growth", "cgf_optimal")]
        lines.append(" & ".join(fields) + r" \\")
    lines += [r"\hline", r"\end{tabular}"]
    save_text("deferred_upper_table.tex", "\n".join(lines) + "\n")


if __name__ == "__main__":
    result = experiment()
    save_text("deferred_comparison.json", json.dumps(result, indent=2) + "\n")
    write_tables(result)
    print(json.dumps(result, indent=2))
